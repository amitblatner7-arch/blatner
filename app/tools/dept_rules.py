    """ביטוי: כמה מילים ברצף, כל אחת עם נטייה, עם מילות קישור אפשריות ביניהן."""
    return r"\s+(?:ל|ב|ה)?".join(PRE + re.escape(norm(x)) + SUF for x in words)

