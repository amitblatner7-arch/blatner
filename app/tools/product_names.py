# -*- coding: utf-8 -*-
"""
ניקוי שמות מוצרים — מקור אמת יחיד לשני הצינורות.

השמות מגיעים מקבצי שקיפות המחירים של הרשתות, ומגיעים מלוכלכים:
סימוני מבצע בכוכביות, גרש הפוך במקום גרש, סימני כיווניות בלתי נראים,
קיצורים קטומים ורווחים כפולים. המשתמשת הראשית של האתר לא מזהה
לפי זה מה המוצר, וזו הייתה תלונה מפורשת.

מכוסה במבחן: מחקר/מבחן-שמות.py
"""
import re

# סימני כיווניות בלתי נראים שמגיעים מהקבצים ומשבשים תצוגה בעברית
INVISIBLE = re.compile(r"[‎‏‪-‮⁦-⁩­]")

# סימון מבצע שהרשת מוסיפה לשם המוצר: *מבצע*, **, *2 ב-20*
PROMO_TAG = re.compile(r"\*[^*]{0,20}\*")

# גרש הפוך ותווי ציטוט חריגים — מוחלפים בגרש תקני
ODD_QUOTES = re.compile(r"[`׳‘’]")

# קיצורים קטומים שהרשת שולחת בלי המשך. הסדר חשוב: הארוך קודם.
ABBREV = [
    (re.compile(r"(?<=\d)\s*גר['\"]?(?![א-ת])"), " גרם "),
    (re.compile(r"(?<=\d)\s*ג['\"]?(?![א-ת])"), " גרם "),
    (re.compile(r"(?<=\d)\s*מ[\"']ל(?![א-ת])"), ' מ"ל '),
    (re.compile(r"(?<=\d)\s*ק[\"']ג(?![א-ת])"), ' ק"ג '),
    (re.compile(r"(?<=\d)\s*ל(?![א-ת])"), " ליטר "),
    (re.compile(r"(?<=\d)\s*יח['\"]?(?![א-ת])"), " יחידות "),
]

MULTISPACE = re.compile(r"\s+")

# אות בודדת תלושה בסוף — שריד של שם שנקטם אצל הרשת ("על רגל מ")
DANGLING = re.compile(r"\s[א-ת]$")


def clean_name(name):
    """מחזיר שם מוצר קריא. בטוח להרצה חוזרת על שם שכבר נוקה."""
    if not name:
        return ""
    s = INVISIBLE.sub("", name)
    s = PROMO_TAG.sub(" ", s)
    s = s.replace("*", " ")
    s = ODD_QUOTES.sub("'", s)
    for rx, rep in ABBREV:
        s = rx.sub(rep, s)
    s = MULTISPACE.sub(" ", s).strip()
    s = s.strip(" .,-'\"")
    # מוסר רק אם נשאר שם בעל משמעות אחרי ההסרה
    if len(s) > 6:
        s = DANGLING.sub("", s).strip()
    return s
